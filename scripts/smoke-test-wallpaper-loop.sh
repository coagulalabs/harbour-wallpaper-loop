# Unit + smoke tests for harbour-wallpaper-loop.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PHONE_HOST="${PHONE_HOST:-192.168.2.3}"
SSH_KEY="${SSH_KEY:-$HOME/.ssh/id_ed25519}"
SSH=(ssh -o BatchMode=yes -o ConnectTimeout=10 -i "$SSH_KEY" "defaultuser@${PHONE_HOST}")

pass=0
fail=0
check() {
  local name="$1"
  shift
  if "$@"; then
    echo "PASS  $name"
    pass=$((pass + 1))
    return 0
  fi
  echo "FAIL  $name"
  fail=$((fail + 1))
  return 1
}

# Host-side content check against a remote file (avoids BusyBox grep quirks).
remote_lacks() {
  local pattern=$1 file=$2
  ! "${SSH[@]}" cat "$file" | grep -q -i -- "$pattern"
}

remote_has() {
  local pattern=$1 file=$2
  "${SSH[@]}" cat "$file" | grep -q -- "$pattern"
}

echo "== unit (host) =="
if python3 "$ROOT/tests/test_imageutil.py"; then
  check "unit suite (python mirror of imageutil.h)" true
else
  check "unit suite (python mirror of imageutil.h)" false
fi

# Optional Qt Test when tooling exists
UNIT_DIR="$ROOT/tests/build-host"
QMAKE_BIN=""
for c in qmake-qt5 qmake /usr/lib/qt5/bin/qmake; do
  if command -v "$c" >/dev/null 2>&1; then
    QMAKE_BIN=$(command -v "$c")
    break
  elif [ -x "$c" ]; then
    QMAKE_BIN=$c
    break
  fi
done
if [ -n "$QMAKE_BIN" ]; then
  rm -rf "$UNIT_DIR"
  mkdir -p "$UNIT_DIR"
  (
    cd "$UNIT_DIR"
    "$QMAKE_BIN" "$ROOT/tests/tst_imageutil.pro"
    make -j"$(nproc)"
    ./tst_imageutil
  )
  check "unit suite (QtTest)" test $? -eq 0
fi

echo
echo "== smoke (phone ${PHONE_HOST}) =="
check "ssh reachable" "${SSH[@]}" true
check "package installed" "${SSH[@]}" rpm -q harbour-wallpaper-loop
check "binary present" "${SSH[@]}" test -x /usr/bin/harbour-wallpaper-loop
check "desktop present" "${SSH[@]}" test -f /usr/share/applications/harbour-wallpaper-loop.desktop
check "qml main present" "${SSH[@]}" test -f /usr/share/harbour-wallpaper-loop/qml/harbour-wallpaper-loop.qml
check "sailjail profile" "${SSH[@]}" test -f /etc/sailjail/applications/harbour-wallpaper-loop.profile
check "user unit installed" \
  "${SSH[@]}" test -f /usr/lib/systemd/user/harbour-wallpaper-loop.service
check "desktop omits video" \
  remote_lacks video /usr/share/applications/harbour-wallpaper-loop.desktop
check "main page mentions Ambience" \
  remote_has Ambience /usr/share/harbour-wallpaper-loop/qml/pages/MainPage.qml
